#!/bin/sh
# Run by hack/lock.sh, in the toolbox image, from controller/. AWX pins its
# venv in requirements/requirements.txt; its Makefile already knows an offline
# mode (PIP_OPTIONS with --no-index), and the git-based requirements beside it
# are built here from submodules instead: django-ansible-base, awx-plugins-core,
# awx_plugins.interfaces and system-certifi. ansible-runner is the release the
# vendor ships rather than AWX's devel branch; supervisor and dumb-init join
# the venv as they do in the vendor image.
set -eu
{
  echo "# Generated by lock-pre.sh from src/requirements/requirements.txt."
  grep -E '^[A-Za-z0-9]' src/requirements/requirements.txt | sed 's/ *#.*//'
  echo "ansible-runner==2.4.3"
  echo "supervisor==4.3.0"
  echo "dumb-init==1.2.5.post1"
} > requirements.in
