#!/bin/sh
# Run by hack/lock.sh, in the toolbox image, from eda/. eda-server pins its
# dependencies in poetry.lock; Red Hat's image installs from a requirements
# file exported from it, plus a short hand-written one. Both are rebuilt here
# from src/ (the eda-server submodule), then merged into requirements.in,
# which hack/lock.sh compiles with hashes for the prefetch.
set -eu

cp -r src /tmp/eda-src
(cd /tmp/eda-src && poetry export --without-hashes -f requirements.txt) > requirements/poetry-export.in

# requirements.in: everything the wheels stage builds, by name and version.
# django-ansible-base is built from its own submodule (eda-server pins it from
# a private repo), psycopg-binary is the dev extra, and certifi is Red Hat's
# system-trust stub, built from the system-certifi submodule.
{
  echo "# Generated by lock-pre.sh from requirements/; edit those, not this."
  grep -v -E '^(django-ansible-base|psycopg-binary|certifi)[ =@]' requirements/poetry-export.in
  grep -v -E '^\s*(#|$)' requirements/manual.in
} > requirements.in
