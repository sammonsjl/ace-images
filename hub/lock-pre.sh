#!/bin/sh
# Run by hack/lock.sh, in the toolbox image, from hub/. galaxy_ng pins the
# standalone deployment in requirements/requirements.standalone.txt; that is
# the list, less django-ansible-base (a git reference there, built from its
# submodule here), certifi (Red Hat's system-trust stub, also a submodule) and
# psycopg's binary extra (wheels only, no sdist to build; the vendor image runs pure
# psycopg on the system libpq instead).
#
# requirements.out is what the final stage installs with --no-deps: the same
# pins by name and version, which is the vendor's arrangement.
set -eu
{
  echo "# Generated by lock-pre.sh from src/requirements/requirements.standalone.txt."
  grep -E '^[A-Za-z0-9]' src/requirements/requirements.standalone.txt | sed 's/ *#.*//' \
    | grep -v -E '^(django-ansible-base|certifi|psycopg-binary)[ =@\[]' \
    | sed 's/^psycopg\[binary\]==/psycopg==/'
} > requirements.in
grep -E '^[A-Za-z0-9]' requirements.in > requirements.out
